import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
VULKAN_DIR = HERE / "external" / "mesa" / "vulkan"
CORE_HEADER = VULKAN_DIR / "vulkan_core.h"
METAL_HEADER = VULKAN_DIR / "vulkan_metal.h"
OUTPUT = HERE / "ctxbridges" / "vk_dispatch_forwarders.h"

