# Implemented by hand in vk_loader_shim.c: they need to track the created instance
# or answer the loader queries the raw drivers cannot.
HANDWRITTEN = {
    "vkCreateInstance",
    "vkGetInstanceProcAddr",
    "vkEnumerateInstanceLayerProperties",
    "vkEnumerateDeviceLayerProperties",
}

HEADER_COMMENT = """// Generated by Natives/gen_vk_dispatch.py - do not edit by hand.
//
// Re-exports the Vulkan commands libMobileGL.dylib links against and forwards each
// one to the driver the shim loaded (AME_VULKAN_DRIVER), so the GL-on-Vulkan
// renderer works with KosmicKrisp as well as with MoltenVK.
"""


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    text = re.sub(r"//[^\n]*", "", text)
    return text


def parse_prototypes(path):
    text = strip_comments(path.read_text(encoding="utf-8"))
    prototypes = {}
    pattern = re.compile(
        r"VKAPI_ATTR\s+([A-Za-z0-9_\s\*]+?)\s+VKAPI_CALL\s+(vk\w+)\s*\(([^;]*?)\)\s*;",
        re.S,
    )
    for match in pattern.finditer(text):
        name = match.group(2)
        prototypes[name] = (" ".join(match.group(1).split()), " ".join(match.group(3).split()))
    return prototypes


def split_parameters(params):
    params = params.strip()
    if not params or params == "void":
        return []
    parts = []
    current = ""
    depth = 0
    for char in params:
        if char == "," and depth == 0:
            parts.append(current.strip())
            current = ""
            continue
        if char in "([":
            depth += 1
        elif char in ")]":
            depth -= 1
        current += char
    parts.append(current.strip())
    return parts


def parameter_name(declaration):
    match = re.search(r"([A-Za-z_]\w*)\s*\[[^\]]*\]\s*$", declaration)
    if match:
        return match.group(1)
    match = re.search(r"([A-Za-z_]\w*)\s*$", declaration)
    return match.group(1) if match else None


def dispatch_argument(declarations, names):
    if not declarations:
        return "VK_NULL_HANDLE"
    first = re.sub(r"\[[^\]]*\]\s*$", "", declarations[0]).strip()
    # A pointer parameter means the argument is not a dispatchable handle: these
    # are the global (instance creation and enumeration) commands.
    if "*" in first:
        return "VK_NULL_HANDLE"
    type_tokens = [token for token in first.split()[:-1] if token != "const"]
    if " ".join(type_tokens) == "VkInstance":
        return names[0]
    # Every other command with a handle takes an instance family or device family
    # dispatchable; resolving with the instance created above works for both.
    return "AMEDispatchInstance()"


def guard_statement(return_type):
    if return_type == "void":
        return "return;"
    if return_type == "VkResult":
        return "return VK_ERROR_INITIALIZATION_FAILED;"
    if return_type == "VkBool32":
        return "return VK_FALSE;"
    return "return (%s)0;" % return_type


def generate_forwarder(name, return_type, declarations, names):
    dispatch = dispatch_argument(declarations, names)
    arguments = ", ".join(names)
    lines = [
        "VKAPI_ATTR %s VKAPI_CALL %s(%s)" % (return_type, name, ", ".join(declarations)),
        "{",
        "    static PFN_%s real;" % name,
        "    if (real == NULL) real = (PFN_%s)(uintptr_t)AMEResolve(\"%s\", %s);" % (name, name, dispatch),
        "    if (real == NULL) %s" % guard_statement(return_type),
    ]
    if return_type == "void":
        lines.append("    real(%s);" % arguments)
    else:
        lines.append("    return real(%s);" % arguments)
    lines.append("}")
    return "\n".join(lines)


def main():
    if not CORE_HEADER.is_file() or not METAL_HEADER.is_file():
        print("vulkan headers not found under %s" % VULKAN_DIR, file=sys.stderr)
        return 1

    prototypes = parse_prototypes(CORE_HEADER)
    prototypes.update(parse_prototypes(METAL_HEADER))

    missing = [name for name in SYMBOLS if name not in prototypes and name not in HANDWRITTEN]
    if missing:
        print("no prototype for: " + ", ".join(missing), file=sys.stderr)
        return 1

    exported = [name for name in SYMBOLS]
    generated = [name for name in SYMBOLS if name not in HANDWRITTEN]

    chunks = [HEADER_COMMENT, "#pragma once\n"]
    for name in generated:
        return_type, params = prototypes[name]
        declarations = split_parameters(params)
        names = [parameter_name(declaration) for declaration in declarations]
        if any(argument is None for argument in names):
            print("could not name the parameters of %s: %s" % (name, params), file=sys.stderr)
            return 1
        chunks.append(generate_forwarder(name, return_type, declarations, names))
    OUTPUT.write_text("\n\n".join(chunks) + "\n", encoding="utf-8")
    print("wrote %s (%d forwarded, %d exported in total)" % (OUTPUT, len(generated), len(exported)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
