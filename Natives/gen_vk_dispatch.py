#!/usr/bin/env python3
"""Generate the Vulkan entry points libame_vulkan.dylib re-exports.

libMobileGL.dylib links the Vulkan driver image directly, and KosmicKrisp (a
Mesa ICD build) only exports the loader interface (vkCreateInstance,
vkGetInstanceProcAddr, ...). The launcher's libame_vulkan.dylib shim has to
export every Vulkan command MobileGL references and forward it to the driver
named by AME_VULKAN_DRIVER.

The symbol list below is what libMobileGL.dylib imported at the MobileGL
submodule revision this repository pins:

    xcrun nm -u Natives/build/libMobileGL.dylib | grep '_vk'

Run this script after updating that submodule:

    python3 Natives/gen_vk_dispatch.py

It parses the Vulkan headers vendored under Natives/external/mesa and rewrites
Natives/ctxbridges/vk_dispatch_forwarders.h.
"""

